def find_docx(name_part: str) -> str:
    for p in glob.glob(os.path.join(BASE, "*.docx")):
        if name_part in os.path.basename(p):
            return p
    raise FileNotFoundError(name_part)


def para_index_by_prefix(doc, prefix: str) -> int | None:
    for i, p in enumerate(doc.paragraphs):
        if p.text.strip().startswith(prefix):
            return i
    return None


def set_para_text(p, text: str) -> None:
    if not p.runs:
        p.text = text
        return
    p.runs[0].text = text
    for r in p.runs[1:]:
        r.text = ""


def replace_from(doc, start_prefix: str, replacements: list[tuple[str, str]]) -> None:
    """Заменяет абзацы, начиная с start_prefix, по порядку old->new."""
    start = para_index_by_prefix(doc, start_prefix)
    if start is None:
        raise RuntimeError(f"Не найден абзац: {start_prefix}")
    idx = start
    for old, new in replacements:
        while idx < len(doc.paragraphs) and not doc.paragraphs[idx].text.strip():
            idx += 1
        if idx >= len(doc.paragraphs):
            raise RuntimeError(f"Нет абзаца для замены: {old[:40]}...")
        cur = doc.paragraphs[idx].text.strip()
        if old and cur != old.strip():
            # допускаем частичное совпадение начала
            if not cur.startswith(old.strip()[:30]):
                print(f"WARN [{idx}]: ожидали '{old[:50]}', есть '{cur[:50]}'")
        set_para_text(doc.paragraphs[idx], new)
        idx += 1


